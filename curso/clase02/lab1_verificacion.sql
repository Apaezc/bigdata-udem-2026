    'O_ORDERKEY,O_ORDERSTATUS,O_TOTALPRICE',
    'Revisa los dos filtros (estado F y precio > 300000), el orden y el LIMIT 5'
  UNION ALL
  SELECT 'EJ4', '★', 4,
