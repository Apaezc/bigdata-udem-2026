-- =====================================================================
-- MINI-CASO · VERIFICACIÓN (autoverificación; Big Data UdeM · Clase 2)
-- =====================================================================
-- QUÉ HACE
--   Compara tus vistas Q1..Q4 (en CURSO.CASO) con la respuesta esperada sobre TPC-H SF10.
--   Devuelve una fila por vista y una fila de resumen. Corre sobre 60 millones de líneas: en
--   X-Small tarda unos segundos.
--
-- CÓMO LEER EL RESULTADO
--   OK         = tu vista da el mismo resultado (mismas filas, mismas columnas y en el mismo
--                orden de columnas).
--   REVISAR    = tu vista existe pero no coincide. Lee la PISTA.
--   PENDIENTE  = todavía tiene la línea SELECT NULL AS PENDIENTE (no escribiste tu SELECT).
--   RESUMEN    = cuántas de las 4 vistas están en OK. Meta: RESUMEN = OK y "4 de 4".
--   TUS_COLUMNAS y COLUMNAS_ESPERADAS = aparecen solo en las filas REVISAR.
--   La lectura del perfil de Q4 no se verifica.
--
-- REQUISITOS
--   - Haber corrido el PASO 0 de caso.sql (rol, warehouse, CURSO.CASO).
--
-- NOTA
--   Este archivo solo crea vistas "marcador" (PENDIENTE) si todavía no existen. No cambia tus
--   vistas existentes. Los importes se comparan con HASH_AGG(*) sobre valores exactos (NUMBER).
-- =====================================================================

-- Marcadores: si una vista aún no existe, se crea con la línea PENDIENTE.
CREATE VIEW IF NOT EXISTS Q1 AS SELECT NULL AS PENDIENTE;
CREATE VIEW IF NOT EXISTS Q2 AS SELECT NULL AS PENDIENTE;
CREATE VIEW IF NOT EXISTS Q3 AS SELECT NULL AS PENDIENTE;
CREATE VIEW IF NOT EXISTS Q4 AS SELECT NULL AS PENDIENTE;

-- =====================================================================
-- CONSULTA FINAL (una sola). Las E1..E4 son la respuesta esperada.
-- =====================================================================
WITH

-- Q1 · respuesta esperada
E1 AS (
  SELECT R.R_NAME AS REGION, COUNT(*) AS PEDIDOS, SUM(O.O_TOTALPRICE) AS MONTO_TOTAL
  FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.ORDERS O JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.CUSTOMER C ON O.O_CUSTKEY = C.C_CUSTKEY
  JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.NATION N ON C.C_NATIONKEY = N.N_NATIONKEY
  JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.REGION R ON N.N_REGIONKEY = R.R_REGIONKEY
  WHERE O.O_ORDERDATE >= '1995-01-01' AND O.O_ORDERDATE < '1996-01-01'
  GROUP BY R.R_NAME
  ORDER BY MONTO_TOTAL DESC, REGION
),

-- Q2 · respuesta esperada
E2 AS (
  SELECT N.N_NAME AS NACION, COUNT(*) AS PEDIDOS, SUM(O.O_TOTALPRICE) AS MONTO_TOTAL
  FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.ORDERS O JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.CUSTOMER C ON O.O_CUSTKEY = C.C_CUSTKEY
  JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.NATION N ON C.C_NATIONKEY = N.N_NATIONKEY
  GROUP BY N.N_NAME
  HAVING COUNT(*) > 600000
  ORDER BY PEDIDOS DESC, NACION
),

-- Q3 · respuesta esperada
E3 AS (
  SELECT R.R_NAME AS REGION, COUNT(*) AS CLIENTES_SIN_PEDIDOS
  FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.CUSTOMER C JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.NATION N ON C.C_NATIONKEY = N.N_NATIONKEY
  JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.REGION R ON N.N_REGIONKEY = R.R_REGIONKEY
  LEFT JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.ORDERS O ON C.C_CUSTKEY = O.O_CUSTKEY
  WHERE O.O_ORDERKEY IS NULL
  GROUP BY R.R_NAME
  ORDER BY CLIENTES_SIN_PEDIDOS DESC, REGION
),

-- Q4 · respuesta esperada
E4 AS (
  SELECT R.R_NAME AS REGION, L.L_SHIPMODE AS MODO_ENVIO, COUNT(*) AS LINEAS,
         SUM(L.L_EXTENDEDPRICE) AS IMPORTE_LINEAS
  FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.LINEITEM L JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.ORDERS O ON L.L_ORDERKEY = O.O_ORDERKEY
  JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.CUSTOMER C ON O.O_CUSTKEY = C.C_CUSTKEY
  JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.NATION N ON C.C_NATIONKEY = N.N_NATIONKEY
  JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF10.REGION R ON N.N_REGIONKEY = R.R_REGIONKEY
  GROUP BY R.R_NAME, L.L_SHIPMODE
  ORDER BY REGION, IMPORTE_LINEAS DESC, MODO_ENVIO
),

-- Un renglón por vista, con las comprobaciones de tu vista.
--   FILAS_OK          : mismo número de filas.
--   VALORES_OK        : mismo HASH_AGG(*) (mismas filas y valores).
--   HASH_PLACEHOLDER  : el HASH_AGG(*) es el del marcador SELECT NULL AS PENDIENTE.
--   COLS_ACTUALES     : nombres de columnas de tu vista, en orden.
--   COLS_ESPERADAS    : nombres de columnas esperados, en orden.
R AS (
  SELECT 'Q1' AS VISTA, 'Q' AS NIVEL, 1 AS K,
    (SELECT COUNT(*) FROM Q1) = (SELECT COUNT(*) FROM E1) AS FILAS_OK,
    (SELECT HASH_AGG(*) FROM Q1) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM E1) AS VALORES_OK,
    (SELECT HASH_AGG(*) FROM Q1) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM (SELECT NULL AS PENDIENTE)) AS HASH_PLACEHOLDER,
    COALESCE((SELECT LISTAGG(COLUMN_NAME, ',') WITHIN GROUP (ORDER BY ORDINAL_POSITION) FROM CURSO.INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'CASO' AND TABLE_NAME = 'Q1'), '') AS COLS_ACTUALES,
    'REGION,PEDIDOS,MONTO_TOTAL' AS COLS_ESPERADAS,
    'Revisa el filtro de 1995, los tres JOIN con ON, SUM(O_TOTALPRICE) y el GROUP BY por región' AS PISTA_MAL

  UNION ALL
  SELECT 'Q2', 'Q', 2,
    (SELECT COUNT(*) FROM Q2) = (SELECT COUNT(*) FROM E2),
    (SELECT HASH_AGG(*) FROM Q2) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM E2),
    (SELECT HASH_AGG(*) FROM Q2) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM (SELECT NULL AS PENDIENTE)),
    COALESCE((SELECT LISTAGG(COLUMN_NAME, ',') WITHIN GROUP (ORDER BY ORDINAL_POSITION) FROM CURSO.INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'CASO' AND TABLE_NAME = 'Q2'), ''),
    'NACION,PEDIDOS,MONTO_TOTAL',
    'Revisa HAVING COUNT(*) > 600000 (seiscientos mil, 6 ceros) y los JOIN con ON'

  UNION ALL
  SELECT 'Q3', 'Q', 3,
    (SELECT COUNT(*) FROM Q3) = (SELECT COUNT(*) FROM E3),
    (SELECT HASH_AGG(*) FROM Q3) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM E3),
    (SELECT HASH_AGG(*) FROM Q3) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM (SELECT NULL AS PENDIENTE)),
    COALESCE((SELECT LISTAGG(COLUMN_NAME, ',') WITHIN GROUP (ORDER BY ORDINAL_POSITION) FROM CURSO.INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'CASO' AND TABLE_NAME = 'Q3'), ''),
    'REGION,CLIENTES_SIN_PEDIDOS',
    'Revisa que sea LEFT JOIN (no INNER), el filtro O.O_ORDERKEY IS NULL'

  UNION ALL
  SELECT 'Q4', 'Q', 4,
    (SELECT COUNT(*) FROM Q4) = (SELECT COUNT(*) FROM E4),
    (SELECT HASH_AGG(*) FROM Q4) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM E4),
    (SELECT HASH_AGG(*) FROM Q4) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM (SELECT NULL AS PENDIENTE)),
    COALESCE((SELECT LISTAGG(COLUMN_NAME, ',') WITHIN GROUP (ORDER BY ORDINAL_POSITION) FROM CURSO.INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'CASO' AND TABLE_NAME = 'Q4'), ''),
    'REGION,MODO_ENVIO,LINEAS,IMPORTE_LINEAS',
    'Revisa los cuatro JOIN, que el importe sea SUM(L.L_EXTENDEDPRICE) (no O_TOTALPRICE) y el GROUP BY región y modo'
),

-- Estado de cada vista: PENDIENTE, OK o REVISAR, con su pista.
F AS (
  SELECT VISTA, NIVEL, K,
    CASE
      WHEN HASH_PLACEHOLDER AND COLS_ACTUALES = 'PENDIENTE' THEN 'PENDIENTE'
      WHEN FILAS_OK AND VALORES_OK AND COLS_ACTUALES = COLS_ESPERADAS THEN 'OK'
      ELSE 'REVISAR'
    END AS RESULTADO,
    CASE
      WHEN HASH_PLACEHOLDER AND COLS_ACTUALES = 'PENDIENTE' THEN 'Pendiente: escribe tu SELECT en la vista'
      WHEN FILAS_OK AND VALORES_OK AND COLS_ACTUALES = COLS_ESPERADAS THEN 'Correcto'
      WHEN COLS_ACTUALES <> COLS_ESPERADAS THEN 'Nombres u orden de columnas distintos al enunciado'
      ELSE PISTA_MAL
    END AS PISTA,
    COLS_ACTUALES,
    COLS_ESPERADAS
  FROM R
)

-- Resultado final: una fila por vista + la fila de resumen.
-- TUS_COLUMNAS y COLUMNAS_ESPERADAS solo se llenan en las filas REVISAR.
SELECT VISTA, NIVEL, RESULTADO, PISTA, TUS_COLUMNAS, COLUMNAS_ESPERADAS
FROM (
  SELECT VISTA, NIVEL, RESULTADO, PISTA,
    CASE WHEN RESULTADO = 'REVISAR' THEN COLS_ACTUALES END AS TUS_COLUMNAS,
    CASE WHEN RESULTADO = 'REVISAR' THEN COLS_ESPERADAS END AS COLUMNAS_ESPERADAS,
    K
  FROM F
  UNION ALL
  SELECT 'RESUMEN', 'Q',
    CASE WHEN COUNT_IF(RESULTADO = 'OK') = 4 THEN 'OK' ELSE 'REVISAR' END,
    CAST(COUNT_IF(RESULTADO = 'OK') AS VARCHAR) || ' de 4 en OK',
    NULL,
    NULL,
    99
  FROM F
)
ORDER BY K;
