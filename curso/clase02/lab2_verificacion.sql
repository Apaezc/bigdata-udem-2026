-- Marcadores: si una vista aún no existe, se crea con la línea PENDIENTE.
CREATE VIEW IF NOT EXISTS EJ1  AS SELECT NULL AS PENDIENTE;
CREATE VIEW IF NOT EXISTS EJ2  AS SELECT NULL AS PENDIENTE;
CREATE VIEW IF NOT EXISTS EJ3  AS SELECT NULL AS PENDIENTE;
CREATE VIEW IF NOT EXISTS EJ4  AS SELECT NULL AS PENDIENTE;
CREATE VIEW IF NOT EXISTS EJ5  AS SELECT NULL AS PENDIENTE;
CREATE VIEW IF NOT EXISTS EJ6  AS SELECT NULL AS PENDIENTE;
CREATE VIEW IF NOT EXISTS EJ7  AS SELECT NULL AS PENDIENTE;
CREATE VIEW IF NOT EXISTS EJ8  AS SELECT NULL AS PENDIENTE;
CREATE VIEW IF NOT EXISTS EJ9  AS SELECT NULL AS PENDIENTE;
CREATE VIEW IF NOT EXISTS EJ10 AS SELECT NULL AS PENDIENTE;

-- =====================================================================
-- CONSULTA FINAL (una sola). Las E1..E10 son la respuesta esperada.
-- =====================================================================
WITH

-- EJ1 ★ · respuesta esperada
E1 AS (
  SELECT O_ORDERSTATUS, COUNT(*) AS PEDIDOS
  FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS
  GROUP BY O_ORDERSTATUS
  ORDER BY O_ORDERSTATUS
),

-- EJ2 ★ · respuesta esperada
E2 AS (
  SELECT O_ORDERPRIORITY, COUNT(*) AS PEDIDOS, SUM(O_TOTALPRICE) AS MONTO_TOTAL
  FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS
  WHERE O_ORDERDATE >= '1995-01-01' AND O_ORDERDATE < '1996-01-01'
  GROUP BY O_ORDERPRIORITY
  ORDER BY O_ORDERPRIORITY
),

-- EJ3 ★ · respuesta esperada
E3 AS (
  SELECT O_CUSTKEY, COUNT(*) AS PEDIDOS
  FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS
  GROUP BY O_CUSTKEY
  HAVING COUNT(*) >= 39
  ORDER BY PEDIDOS DESC, O_CUSTKEY
),

-- EJ4 ★ · respuesta esperada
E4 AS (
  SELECT C_MKTSEGMENT, COUNT(*) AS CLIENTES, ROUND(AVG(C_ACCTBAL), 2) AS SALDO_PROMEDIO,
         MAX(C_ACCTBAL) AS SALDO_MAXIMO
  FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.CUSTOMER
  GROUP BY C_MKTSEGMENT
  ORDER BY C_MKTSEGMENT
),

-- EJ5 ★ · respuesta esperada
E5 AS (
  SELECT C.C_CUSTKEY, C.C_NAME, N.N_NAME
  FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.CUSTOMER C JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.NATION N ON C.C_NATIONKEY = N.N_NATIONKEY
  ORDER BY C.C_CUSTKEY
  LIMIT 5
),

-- EJ6 ★ · respuesta esperada
E6 AS (
  SELECT N.N_NAME, COUNT(*) AS CLIENTES
  FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.CUSTOMER C JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.NATION N ON C.C_NATIONKEY = N.N_NATIONKEY
  GROUP BY N.N_NAME
  ORDER BY CLIENTES DESC, N.N_NAME
  LIMIT 5
),

-- EJ7 ★★ · respuesta esperada
E7 AS (
  SELECT O.O_ORDERPRIORITY, COUNT(*) AS FILAS_JOIN, SUM(O.O_TOTALPRICE) AS MONTO_INFLADO
  FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS O JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.LINEITEM L ON O.O_ORDERKEY = L.L_ORDERKEY
  WHERE O.O_ORDERDATE >= '1995-01-01' AND O.O_ORDERDATE < '1996-01-01'
  GROUP BY O.O_ORDERPRIORITY
  ORDER BY O.O_ORDERPRIORITY
),

-- EJ8 ★★ · respuesta esperada
E8 AS (
  SELECT O.O_ORDERPRIORITY, COUNT(DISTINCT O.O_ORDERKEY) AS PEDIDOS,
         ROUND(SUM(L.L_EXTENDEDPRICE*(1-L.L_DISCOUNT)*(1+L.L_TAX)), 2) AS IMPORTE_LINEAS
  FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS O JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.LINEITEM L ON O.O_ORDERKEY = L.L_ORDERKEY
  WHERE O.O_ORDERDATE >= '1995-01-01' AND O.O_ORDERDATE < '1996-01-01'
  GROUP BY O.O_ORDERPRIORITY
  ORDER BY O.O_ORDERPRIORITY
),

-- EJ9 ★★ · respuesta esperada
E9 AS (
  SELECT C.C_MKTSEGMENT, COUNT(*) AS CLIENTES_SIN_PEDIDOS
  FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.CUSTOMER C LEFT JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS O ON C.C_CUSTKEY = O.O_CUSTKEY
  WHERE O.O_ORDERKEY IS NULL
  GROUP BY C.C_MKTSEGMENT
  ORDER BY C.C_MKTSEGMENT
),

-- EJ10 ★★★ · respuesta esperada
E10 AS (
  SELECT N.N_NAME, COUNT(DISTINCT C.C_CUSTKEY) AS CLIENTES, COUNT(O.O_ORDERKEY) AS PEDIDOS
  FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.NATION N JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.CUSTOMER C ON N.N_NATIONKEY = C.C_NATIONKEY
  LEFT JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS O ON C.C_CUSTKEY = O.O_CUSTKEY
  GROUP BY N.N_NAME
  HAVING COUNT(O.O_ORDERKEY) > 60000
  ORDER BY PEDIDOS DESC, N.N_NAME
),

-- Un renglón por ejercicio, con las comprobaciones de tu vista.
--   FILAS_OK          : mismo número de filas.
--   VALORES_OK        : mismo HASH_AGG(*) (mismas filas y valores).
--   HASH_PLACEHOLDER  : el HASH_AGG(*) es el del marcador SELECT NULL AS PENDIENTE.
--   COLS_ACTUALES     : nombres de columnas de tu vista, en orden.
--   COLS_ESPERADAS    : nombres de columnas esperados, en orden.
R AS (
  SELECT 'EJ1' AS EJERCICIO, '★' AS NIVEL, 1 AS K,
    (SELECT COUNT(*) FROM EJ1) = (SELECT COUNT(*) FROM E1) AS FILAS_OK,
    (SELECT HASH_AGG(*) FROM EJ1) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM E1) AS VALORES_OK,
    (SELECT HASH_AGG(*) FROM EJ1) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM (SELECT NULL AS PENDIENTE)) AS HASH_PLACEHOLDER,
    COALESCE((SELECT LISTAGG(COLUMN_NAME, ',') WITHIN GROUP (ORDER BY ORDINAL_POSITION) FROM CURSO.INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'LAB2' AND TABLE_NAME = 'EJ1'), '') AS COLS_ACTUALES,
    'O_ORDERSTATUS,PEDIDOS' AS COLS_ESPERADAS,
    'Revisa el GROUP BY por O_ORDERSTATUS, el alias PEDIDOS y el ORDER BY' AS PISTA_MAL

  UNION ALL
  SELECT 'EJ2', '★', 2,
    (SELECT COUNT(*) FROM EJ2) = (SELECT COUNT(*) FROM E2),
    (SELECT HASH_AGG(*) FROM EJ2) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM E2),
    (SELECT HASH_AGG(*) FROM EJ2) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM (SELECT NULL AS PENDIENTE)),
    COALESCE((SELECT LISTAGG(COLUMN_NAME, ',') WITHIN GROUP (ORDER BY ORDINAL_POSITION) FROM CURSO.INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'LAB2' AND TABLE_NAME = 'EJ2'), ''),
    'O_ORDERPRIORITY,PEDIDOS,MONTO_TOTAL',
    'Revisa el filtro de fechas de 1995 (sin <= ), COUNT(*), SUM(O_TOTALPRICE) y el GROUP BY'

  UNION ALL
  SELECT 'EJ3', '★', 3,
    (SELECT COUNT(*) FROM EJ3) = (SELECT COUNT(*) FROM E3),
    (SELECT HASH_AGG(*) FROM EJ3) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM E3),
    (SELECT HASH_AGG(*) FROM EJ3) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM (SELECT NULL AS PENDIENTE)),
    COALESCE((SELECT LISTAGG(COLUMN_NAME, ',') WITHIN GROUP (ORDER BY ORDINAL_POSITION) FROM CURSO.INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'LAB2' AND TABLE_NAME = 'EJ3'), ''),
    'O_CUSTKEY,PEDIDOS',
    'Revisa HAVING COUNT(*) >= 39 (no WHERE) y el GROUP BY por O_CUSTKEY'

  UNION ALL
  SELECT 'EJ4', '★', 4,
    (SELECT COUNT(*) FROM EJ4) = (SELECT COUNT(*) FROM E4),
    (SELECT HASH_AGG(*) FROM EJ4) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM E4),
    (SELECT HASH_AGG(*) FROM EJ4) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM (SELECT NULL AS PENDIENTE)),
    COALESCE((SELECT LISTAGG(COLUMN_NAME, ',') WITHIN GROUP (ORDER BY ORDINAL_POSITION) FROM CURSO.INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'LAB2' AND TABLE_NAME = 'EJ4'), ''),
    'C_MKTSEGMENT,CLIENTES,SALDO_PROMEDIO,SALDO_MAXIMO',
    'Revisa AVG con ROUND(..., 2), MAX(C_ACCTBAL) y el GROUP BY por segmento'

  UNION ALL
  SELECT 'EJ5', '★', 5,
    (SELECT COUNT(*) FROM EJ5) = (SELECT COUNT(*) FROM E5),
    (SELECT HASH_AGG(*) FROM EJ5) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM E5),
    (SELECT HASH_AGG(*) FROM EJ5) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM (SELECT NULL AS PENDIENTE)),
    COALESCE((SELECT LISTAGG(COLUMN_NAME, ',') WITHIN GROUP (ORDER BY ORDINAL_POSITION) FROM CURSO.INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'LAB2' AND TABLE_NAME = 'EJ5'), ''),
    'C_CUSTKEY,C_NAME,N_NAME',
    'Revisa el ON (C_NATIONKEY = N_NATIONKEY), el ORDER BY C_CUSTKEY y el LIMIT 5'

  UNION ALL
  SELECT 'EJ6', '★', 6,
    (SELECT COUNT(*) FROM EJ6) = (SELECT COUNT(*) FROM E6),
    (SELECT HASH_AGG(*) FROM EJ6) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM E6),
    (SELECT HASH_AGG(*) FROM EJ6) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM (SELECT NULL AS PENDIENTE)),
    COALESCE((SELECT LISTAGG(COLUMN_NAME, ',') WITHIN GROUP (ORDER BY ORDINAL_POSITION) FROM CURSO.INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'LAB2' AND TABLE_NAME = 'EJ6'), ''),
    'N_NAME,CLIENTES',
    'Revisa el JOIN con ON, el GROUP BY por N_NAME, el orden (CLIENTES DESC, N_NAME) y el LIMIT 5'

  UNION ALL
  SELECT 'EJ7', '★★', 7,
    (SELECT COUNT(*) FROM EJ7) = (SELECT COUNT(*) FROM E7),
    (SELECT HASH_AGG(*) FROM EJ7) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM E7),
    (SELECT HASH_AGG(*) FROM EJ7) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM (SELECT NULL AS PENDIENTE)),
    COALESCE((SELECT LISTAGG(COLUMN_NAME, ',') WITHIN GROUP (ORDER BY ORDINAL_POSITION) FROM CURSO.INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'LAB2' AND TABLE_NAME = 'EJ7'), ''),
    'O_ORDERPRIORITY,FILAS_JOIN,MONTO_INFLADO',
    'Revisa que uses COUNT(*) y SUM(O.O_TOTALPRICE) sobre el JOIN (sin DISTINCT) y el filtro de 1995'

  UNION ALL
  SELECT 'EJ8', '★★', 8,
    (SELECT COUNT(*) FROM EJ8) = (SELECT COUNT(*) FROM E8),
    (SELECT HASH_AGG(*) FROM EJ8) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM E8),
    (SELECT HASH_AGG(*) FROM EJ8) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM (SELECT NULL AS PENDIENTE)),
    COALESCE((SELECT LISTAGG(COLUMN_NAME, ',') WITHIN GROUP (ORDER BY ORDINAL_POSITION) FROM CURSO.INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'LAB2' AND TABLE_NAME = 'EJ8'), ''),
    'O_ORDERPRIORITY,PEDIDOS,IMPORTE_LINEAS',
    'Revisa COUNT(DISTINCT O.O_ORDERKEY), la expresión L_EXTENDEDPRICE*(1-L_DISCOUNT)*(1+L_TAX) y ROUND(..., 2)'

  UNION ALL
  SELECT 'EJ9', '★★', 9,
    (SELECT COUNT(*) FROM EJ9) = (SELECT COUNT(*) FROM E9),
    (SELECT HASH_AGG(*) FROM EJ9) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM E9),
    (SELECT HASH_AGG(*) FROM EJ9) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM (SELECT NULL AS PENDIENTE)),
    COALESCE((SELECT LISTAGG(COLUMN_NAME, ',') WITHIN GROUP (ORDER BY ORDINAL_POSITION) FROM CURSO.INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'LAB2' AND TABLE_NAME = 'EJ9'), ''),
    'C_MKTSEGMENT,CLIENTES_SIN_PEDIDOS',
    'Revisa que sea LEFT JOIN (no INNER) y el filtro O.O_ORDERKEY IS NULL'

  UNION ALL
  SELECT 'EJ10', '★★★', 10,
    (SELECT COUNT(*) FROM EJ10) = (SELECT COUNT(*) FROM E10),
    (SELECT HASH_AGG(*) FROM EJ10) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM E10),
    (SELECT HASH_AGG(*) FROM EJ10) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM (SELECT NULL AS PENDIENTE)),
    COALESCE((SELECT LISTAGG(COLUMN_NAME, ',') WITHIN GROUP (ORDER BY ORDINAL_POSITION) FROM CURSO.INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'LAB2' AND TABLE_NAME = 'EJ10'), ''),
    'N_NAME,CLIENTES,PEDIDOS',
    'Revisa COUNT(O.O_ORDERKEY) (no COUNT(*)), COUNT(DISTINCT C.C_CUSTKEY), HAVING > 60000 y el LEFT JOIN'
),

-- Estado de cada ejercicio: PENDIENTE, OK o REVISAR, con su pista.
F AS (
  SELECT EJERCICIO, NIVEL, K,
    CASE
      WHEN HASH_PLACEHOLDER AND COLS_ACTUALES = 'PENDIENTE' THEN 'PENDIENTE'
      WHEN FILAS_OK AND VALORES_OK AND COLS_ACTUALES = COLS_ESPERADAS THEN 'OK'
      ELSE 'REVISAR'
    END AS RESULTADO,
    CASE
      WHEN HASH_PLACEHOLDER AND COLS_ACTUALES = 'PENDIENTE' THEN 'Pendiente: escribe tu SELECT en la vista'
      WHEN FILAS_OK AND VALORES_OK AND COLS_ACTUALES = COLS_ESPERADAS THEN 'Correcto'
      WHEN COLS_ACTUALES <> COLS_ESPERADAS THEN 'Nombres u orden de columnas distintos al enunciado'
      ELSE PISTA_MAL
    END AS PISTA,
    COLS_ACTUALES,
    COLS_ESPERADAS
  FROM R
)

-- Resultado final: una fila por ejercicio + la fila de resumen.
-- TUS_COLUMNAS y COLUMNAS_ESPERADAS solo se llenan en las filas REVISAR.
SELECT EJERCICIO, NIVEL, RESULTADO, PISTA, TUS_COLUMNAS, COLUMNAS_ESPERADAS
FROM (
  SELECT EJERCICIO, NIVEL, RESULTADO, PISTA,
    CASE WHEN RESULTADO = 'REVISAR' THEN COLS_ACTUALES END AS TUS_COLUMNAS,
    CASE WHEN RESULTADO = 'REVISAR' THEN COLS_ESPERADAS END AS COLUMNAS_ESPERADAS,
    K
  FROM F
  UNION ALL
  SELECT 'RESUMEN', '★',
    CASE WHEN COUNT_IF(RESULTADO = 'OK' AND NIVEL = '★') = 6 THEN 'OK' ELSE 'REVISAR' END,
    CAST(COUNT_IF(RESULTADO = 'OK' AND NIVEL = '★') AS VARCHAR) || ' de 6 ★ en OK',
    NULL,
    NULL,
    99
  FROM F
)
ORDER BY K;
