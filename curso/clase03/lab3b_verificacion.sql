-- =====================================================================
-- LAB 3B · VERIFICACIÓN (autoverificación; Big Data UdeM · Clase 3)
-- =====================================================================
-- QUÉ HACE
--   Compara tus vistas B1..B5 (en CURSO.LAB3B) con la respuesta esperada. Devuelve una fila por
--   ejercicio y una fila de resumen. En B1, B2 y B3 revisa además que la vista use QUALIFY.
--
-- CÓMO LEER EL RESULTADO
--   OK         = tu vista da el mismo resultado (mismas filas, mismas columnas y en el mismo
--                orden de columnas) y, en B1 a B3, usa QUALIFY.
--   REVISAR    = tu vista existe pero no coincide, o no usa QUALIFY. Lee la PISTA.
--   PENDIENTE  = todavía tiene la línea SELECT NULL AS PENDIENTE (no escribiste tu SELECT).
--   RESUMEN    = cuántos de los 4 ★ están en OK. Meta: RESUMEN = OK y "4 de 4".
--   TUS_COLUMNAS y COLUMNAS_ESPERADAS = aparecen solo en las filas REVISAR, para comparar los
--                nombres de columnas.
--
-- REQUISITOS
--   - Haber corrido el PASO 0 de lab3b.sql (rol, warehouse, CURSO.LAB3B).
--
-- NOTA
--   Este archivo solo crea vistas "marcador" (PENDIENTE) si todavía no existen, para que la
--   verificación nunca falle por una vista faltante. No cambia tus vistas existentes.
--   La revisión de QUALIFY lee la definición de la vista con GET_DDL: es superficial (un
--   comentario con la palabra QUALIFY también la satisface).
--   Los importes se comparan con ROUND(..., 2) en la respuesta esperada.
-- =====================================================================

-- Marcadores: si un objeto aún no existe, se crea con la línea PENDIENTE.
CREATE VIEW IF NOT EXISTS B1           AS SELECT NULL AS PENDIENTE;
CREATE VIEW IF NOT EXISTS B2           AS SELECT NULL AS PENDIENTE;
CREATE VIEW IF NOT EXISTS B3           AS SELECT NULL AS PENDIENTE;
CREATE VIEW IF NOT EXISTS B4           AS SELECT NULL AS PENDIENTE;
CREATE VIEW IF NOT EXISTS B5           AS SELECT NULL AS PENDIENTE;

-- =====================================================================
-- CONSULTA FINAL (una sola). Las E1..En son la respuesta esperada.
-- =====================================================================
WITH

-- B1 ★ · respuesta esperada
E1 AS (
  SELECT O_ORDERPRIORITY, O_ORDERKEY, O_TOTALPRICE, RN
  FROM (SELECT O_ORDERPRIORITY, O_ORDERKEY, O_TOTALPRICE,
               ROW_NUMBER() OVER (PARTITION BY O_ORDERPRIORITY
                                  ORDER BY O_TOTALPRICE DESC, O_ORDERKEY) AS RN
        FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS)
  WHERE RN <= 3
  ORDER BY O_ORDERPRIORITY, RN
),

-- B2 ★ · respuesta esperada
E2 AS (
  SELECT O_CUSTKEY, O_ORDERKEY, O_ORDERDATE
  FROM (SELECT O_CUSTKEY, O_ORDERKEY, O_ORDERDATE,
               ROW_NUMBER() OVER (PARTITION BY O_CUSTKEY
                                  ORDER BY O_ORDERDATE DESC, O_ORDERKEY DESC) AS RN
        FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS)
  WHERE RN = 1
  ORDER BY O_CUSTKEY
),

-- B3 ★ · respuesta esperada
E3 AS (
  SELECT MES, MONTO, MONTO_ANTERIOR, VARIACION_PCT
  FROM (SELECT MES, MONTO,
               LAG(MONTO) OVER (ORDER BY MES) AS MONTO_ANTERIOR,
               ROUND((MONTO - LAG(MONTO) OVER (ORDER BY MES))
                     / LAG(MONTO) OVER (ORDER BY MES) * 100, 2) AS VARIACION_PCT
        FROM (SELECT DATE_TRUNC('month', O_ORDERDATE) AS MES, SUM(O_TOTALPRICE) AS MONTO
              FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS
              WHERE O_ORDERDATE >= '1995-01-01' AND O_ORDERDATE < '1996-01-01'
              GROUP BY DATE_TRUNC('month', O_ORDERDATE)))
  WHERE VARIACION_PCT < 0
  ORDER BY MES
),

-- B4 ★ · respuesta esperada
E4 AS (
  WITH POR_ESTADO AS (SELECT O_ORDERSTATUS, COUNT(*) AS PEDIDOS, AVG(O_TOTALPRICE) AS PROM
                      FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS
                      GROUP BY O_ORDERSTATUS)
  SELECT ROUND(AVG(PROM), 2) AS PROM_DE_PROMEDIOS,
         ROUND((SELECT AVG(O_TOTALPRICE) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS), 2) AS PROM_DIRECTO,
         ROUND(SUM(PEDIDOS * PROM) / SUM(PEDIDOS), 2) AS PROM_PONDERADO,
         ROUND((AVG(PROM) - (SELECT AVG(O_TOTALPRICE) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS))
               / (SELECT AVG(O_TOTALPRICE) FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS) * 100, 2) AS DIFERENCIA_PCT
  FROM POR_ESTADO
),

-- B5 ★★ · respuesta esperada
E5 AS (
  WITH ING AS (SELECT L_ORDERKEY, SUM(L_EXTENDEDPRICE * (1 - L_DISCOUNT)) AS INGRESO_PEDIDO
               FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.LINEITEM
               GROUP BY L_ORDERKEY)
  SELECT R.R_NAME, ROUND(SUM(I.INGRESO_PEDIDO), 2) AS INGRESO
  FROM ING I
  JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS O ON I.L_ORDERKEY = O.O_ORDERKEY
  JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.CUSTOMER C ON O.O_CUSTKEY = C.C_CUSTKEY
  JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.NATION N ON C.C_NATIONKEY = N.N_NATIONKEY
  JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.REGION R ON N.N_REGIONKEY = R.R_REGIONKEY
  GROUP BY R.R_NAME
  ORDER BY R.R_NAME
),

-- Un renglón por ejercicio, con las comprobaciones de tus objetos.
--   FILAS_OK          : mismo número de filas.
--   VALORES_OK        : mismo HASH_AGG(*) (mismas filas y valores).
--   PEND              : el objeto todavía es el marcador SELECT NULL AS PENDIENTE.
--   COLS_ACTUALES     : nombres de columnas de tu objeto, en orden.
--   COLS_ESPERADAS    : nombres de columnas esperados, en orden.
--   EXTRA_OK          : comprobación adicional del ejercicio (estilo o tabla auxiliar).
R AS (
SELECT 'B1' AS EJERCICIO, '★' AS NIVEL, 1 AS K,
    (SELECT COUNT(*) FROM B1) = (SELECT COUNT(*) FROM E1) AS FILAS_OK,
    (SELECT HASH_AGG(*) FROM B1) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM E1) AS VALORES_OK,
    (SELECT HASH_AGG(*) FROM B1) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM (SELECT NULL AS PENDIENTE)) AND COALESCE((SELECT LISTAGG(COLUMN_NAME, ',') WITHIN GROUP (ORDER BY ORDINAL_POSITION) FROM CURSO.INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'LAB3B' AND TABLE_NAME = 'B1'), '') = 'PENDIENTE' AS PEND,
    COALESCE((SELECT LISTAGG(COLUMN_NAME, ',') WITHIN GROUP (ORDER BY ORDINAL_POSITION) FROM CURSO.INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'LAB3B' AND TABLE_NAME = 'B1'), '') AS COLS_ACTUALES,
    'O_ORDERPRIORITY,O_ORDERKEY,O_TOTALPRICE,RN' AS COLS_ESPERADAS,
    CONTAINS(UPPER(GET_DDL('VIEW', 'B1')), 'QUALIFY') AS EXTRA_OK,
    'Revisa ROW_NUMBER con PARTITION BY O_ORDERPRIORITY, el desempate por O_ORDERKEY y el filtro RN <= 3' AS PISTA_MAL,
    'Usa QUALIFY y no una subconsulta' AS PISTA_EXTRA
  UNION ALL
SELECT 'B2' AS EJERCICIO, '★' AS NIVEL, 2 AS K,
    (SELECT COUNT(*) FROM B2) = (SELECT COUNT(*) FROM E2) AS FILAS_OK,
    (SELECT HASH_AGG(*) FROM B2) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM E2) AS VALORES_OK,
    (SELECT HASH_AGG(*) FROM B2) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM (SELECT NULL AS PENDIENTE)) AND COALESCE((SELECT LISTAGG(COLUMN_NAME, ',') WITHIN GROUP (ORDER BY ORDINAL_POSITION) FROM CURSO.INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'LAB3B' AND TABLE_NAME = 'B2'), '') = 'PENDIENTE' AS PEND,
    COALESCE((SELECT LISTAGG(COLUMN_NAME, ',') WITHIN GROUP (ORDER BY ORDINAL_POSITION) FROM CURSO.INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'LAB3B' AND TABLE_NAME = 'B2'), '') AS COLS_ACTUALES,
    'O_CUSTKEY,O_ORDERKEY,O_ORDERDATE' AS COLS_ESPERADAS,
    CONTAINS(UPPER(GET_DDL('VIEW', 'B2')), 'QUALIFY') AS EXTRA_OK,
    'Revisa el orden descendente por fecha y clave y el filtro RN = 1' AS PISTA_MAL,
    'Usa QUALIFY y no una subconsulta' AS PISTA_EXTRA
  UNION ALL
SELECT 'B3' AS EJERCICIO, '★' AS NIVEL, 3 AS K,
    (SELECT COUNT(*) FROM B3) = (SELECT COUNT(*) FROM E3) AS FILAS_OK,
    (SELECT HASH_AGG(*) FROM B3) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM E3) AS VALORES_OK,
    (SELECT HASH_AGG(*) FROM B3) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM (SELECT NULL AS PENDIENTE)) AND COALESCE((SELECT LISTAGG(COLUMN_NAME, ',') WITHIN GROUP (ORDER BY ORDINAL_POSITION) FROM CURSO.INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'LAB3B' AND TABLE_NAME = 'B3'), '') = 'PENDIENTE' AS PEND,
    COALESCE((SELECT LISTAGG(COLUMN_NAME, ',') WITHIN GROUP (ORDER BY ORDINAL_POSITION) FROM CURSO.INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'LAB3B' AND TABLE_NAME = 'B3'), '') AS COLS_ACTUALES,
    'MES,MONTO,MONTO_ANTERIOR,VARIACION_PCT' AS COLS_ESPERADAS,
    CONTAINS(UPPER(GET_DDL('VIEW', 'B3')), 'QUALIFY') AS EXTRA_OK,
    'Revisa LAG sobre la suma del mes, el WHERE de 1995 antes de agrupar y que solo queden los meses con variación negativa' AS PISTA_MAL,
    'Usa QUALIFY y no una subconsulta' AS PISTA_EXTRA
  UNION ALL
SELECT 'B4' AS EJERCICIO, '★' AS NIVEL, 4 AS K,
    (SELECT COUNT(*) FROM B4) = (SELECT COUNT(*) FROM E4) AS FILAS_OK,
    (SELECT HASH_AGG(*) FROM B4) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM E4) AS VALORES_OK,
    (SELECT HASH_AGG(*) FROM B4) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM (SELECT NULL AS PENDIENTE)) AND COALESCE((SELECT LISTAGG(COLUMN_NAME, ',') WITHIN GROUP (ORDER BY ORDINAL_POSITION) FROM CURSO.INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'LAB3B' AND TABLE_NAME = 'B4'), '') = 'PENDIENTE' AS PEND,
    COALESCE((SELECT LISTAGG(COLUMN_NAME, ',') WITHIN GROUP (ORDER BY ORDINAL_POSITION) FROM CURSO.INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'LAB3B' AND TABLE_NAME = 'B4'), '') AS COLS_ACTUALES,
    'PROM_DE_PROMEDIOS,PROM_DIRECTO,PROM_PONDERADO,DIFERENCIA_PCT' AS COLS_ESPERADAS,
    TRUE AS EXTRA_OK,
    'Revisa SUM(PEDIDOS * PROM) / SUM(PEDIDOS) y la fórmula de DIFERENCIA_PCT' AS PISTA_MAL,
    '' AS PISTA_EXTRA
  UNION ALL
SELECT 'B5' AS EJERCICIO, '★★' AS NIVEL, 5 AS K,
    (SELECT COUNT(*) FROM B5) = (SELECT COUNT(*) FROM E5) AS FILAS_OK,
    (SELECT HASH_AGG(*) FROM B5) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM E5) AS VALORES_OK,
    (SELECT HASH_AGG(*) FROM B5) IS NOT DISTINCT FROM (SELECT HASH_AGG(*) FROM (SELECT NULL AS PENDIENTE)) AND COALESCE((SELECT LISTAGG(COLUMN_NAME, ',') WITHIN GROUP (ORDER BY ORDINAL_POSITION) FROM CURSO.INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'LAB3B' AND TABLE_NAME = 'B5'), '') = 'PENDIENTE' AS PEND,
    COALESCE((SELECT LISTAGG(COLUMN_NAME, ',') WITHIN GROUP (ORDER BY ORDINAL_POSITION) FROM CURSO.INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'LAB3B' AND TABLE_NAME = 'B5'), '') AS COLS_ACTUALES,
    'R_NAME,INGRESO' AS COLS_ESPERADAS,
    TRUE AS EXTRA_OK,
    'Revisa las cuatro condiciones ON y la fórmula del ingreso' AS PISTA_MAL,
    '' AS PISTA_EXTRA
),

-- Estado de cada ejercicio: PENDIENTE, OK o REVISAR, con su pista.
F AS (
  SELECT EJERCICIO, NIVEL, K,
    CASE
      WHEN PEND THEN 'PENDIENTE'
      WHEN FILAS_OK AND VALORES_OK AND COLS_ACTUALES = COLS_ESPERADAS AND EXTRA_OK THEN 'OK'
      ELSE 'REVISAR'
    END AS RESULTADO,
    CASE
      WHEN PEND THEN 'Pendiente: escribe tu SELECT en el marcador'
      WHEN FILAS_OK AND VALORES_OK AND COLS_ACTUALES = COLS_ESPERADAS AND EXTRA_OK THEN 'Correcto'
      WHEN COLS_ACTUALES <> COLS_ESPERADAS THEN 'Nombres u orden de columnas distintos al enunciado'
      WHEN FILAS_OK AND VALORES_OK AND NOT EXTRA_OK THEN PISTA_EXTRA
      ELSE PISTA_MAL
    END AS PISTA,
    COLS_ACTUALES,
    COLS_ESPERADAS
  FROM R
)

-- Resultado final: una fila por ejercicio + la fila de resumen.
-- TUS_COLUMNAS y COLUMNAS_ESPERADAS solo se llenan en las filas REVISAR.
SELECT EJERCICIO, NIVEL, RESULTADO, PISTA, TUS_COLUMNAS, COLUMNAS_ESPERADAS
FROM (
  SELECT EJERCICIO, NIVEL, RESULTADO, PISTA,
    CASE WHEN RESULTADO = 'REVISAR' THEN COLS_ACTUALES END AS TUS_COLUMNAS,
    CASE WHEN RESULTADO = 'REVISAR' THEN COLS_ESPERADAS END AS COLUMNAS_ESPERADAS,
    K
  FROM F
  UNION ALL
  SELECT 'RESUMEN', '★',
    CASE WHEN COUNT_IF(RESULTADO = 'OK' AND NIVEL = '★') = 4 THEN 'OK' ELSE 'REVISAR' END,
    CAST(COUNT_IF(RESULTADO = 'OK' AND NIVEL = '★') AS VARCHAR) || ' de 4 ★ en OK',
    NULL,
    NULL,
    99
  FROM F
)
ORDER BY K;
