         ROUND(SUM(L.L_EXTENDEDPRICE * (1 - L.L_DISCOUNT)), 2) AS INGRESO
  FROM SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.LINEITEM L
  JOIN SNOWFLAKE_SAMPLE_DATA.TPCH_SF1.ORDERS O ON L.L_ORDERKEY = O.O_ORDERKEY
  WHERE O.O_CUSTKEY = 102022
  GROUP BY 1
  ORDER BY 1
),

-- Cargas marcadas LAB3C en este esquema, de las últimas 24 horas (una fila por sentencia).
-- TABLA es el nombre de la tabla creada; se ignoran las cargas del marcador PENDIENTE.
H AS (
  SELECT UPPER(SPLIT_PART(REGEXP_SUBSTR(QUERY_TEXT, $$TABLE\s+([\w.]+)$$, 1, 1, 'i', 1), '.', -1)) AS TABLA
  FROM TABLE(INFORMATION_SCHEMA.QUERY_HISTORY(RESULT_LIMIT => 10000,
             END_TIME_RANGE_START => DATEADD('day', -1, CURRENT_TIMESTAMP())))
  WHERE QUERY_TAG = 'LAB3C'
    AND QUERY_TYPE = 'CREATE_TABLE_AS_SELECT'
    AND EXECUTION_STATUS = 'SUCCESS'
    AND DATABASE_NAME = CURRENT_DATABASE()
    AND SCHEMA_NAME = 'LAB3C'
    AND NOT CONTAINS(REGEXP_REPLACE(UPPER(QUERY_TEXT), $$\s+$$, ' '), 'SELECT NULL AS PENDIENTE')
),

MARCA AS (
  SELECT
    COUNT(DISTINCT CASE WHEN TABLA IN ('DIM_CLIENTE', 'FACT_LINEITEM') THEN TABLA END) AS HECHAS_POR_TI,
    COUNT(DISTINCT CASE WHEN TABLA IN ('DIM_CLIENTE', 'DIM_FECHA', 'FACT_LINEITEM') THEN TABLA END) AS CARGAS
  FROM H
),
MARCA_R AS (
  SELECT
    CASE WHEN HECHAS_POR_TI = 0 THEN 'PENDIENTE' WHEN CARGAS = 3 THEN 'OK' ELSE 'REVISAR' END AS RESULTADO,
    CASE WHEN HECHAS_POR_TI = 0 THEN 'Sin cargas tuyas con la marca LAB3C: corre ALTER SESSION SET QUERY_TAG = ''LAB3C'' y carga las tablas'
         WHEN CARGAS = 3 THEN 'Correcto: las tres cargas tienen la marca LAB3C'
         ELSE 'Faltan cargas con la marca LAB3C (' || CAST(CARGAS AS VARCHAR) || ' de 3): corre el Paso 1 en la misma hoja y repite el CREATE TABLE' END AS PISTA
  FROM MARCA
),

-- Un renglón por ejercicio, con las comprobaciones de tus objetos.
--   FILAS_OK          : mismo número de filas.
--   VALORES_OK        : mismo HASH_AGG(*) (mismas filas y valores).
--   PEND              : el objeto todavía es el marcador SELECT NULL AS PENDIENTE.
--   COLS_ACTUALES     : nombres de columnas de tu objeto, en orden.
--   COLS_ESPERADAS    : nombres de columnas esperados, en orden.
--   EXTRA_OK          : comprobación adicional del ejercicio (estilo o tabla auxiliar).
R AS (
SELECT 'C1' AS EJERCICIO, '★' AS NIVEL, 1 AS K,
