    COALESCE((SELECT LISTAGG(COLUMN_NAME, ',') WITHIN GROUP (ORDER BY ORDINAL_POSITION) FROM CURSO.INFORMATION_SCHEMA.COLUMNS WHERE TABLE_SCHEMA = 'LAB3C' AND TABLE_NAME = 'FACT_LINEITEM'), '') AS COLS_ACTUALES,
