--   REVISAR    = tu vista existe pero no coincide. Lee la PISTA.
--   PENDIENTE  = todavía tiene la línea SELECT NULL AS PENDIENTE (no escribiste tu SELECT).
--   RESUMEN    = cuántos de los 5 ★ están en OK. Meta: RESUMEN = OK y "5 de 5".
