--
-- REQUISITOS
--   - Haber corrido el PASO 0 de lab3a.sql (rol, warehouse, CURSO.LAB3A).
--
-- NOTA
--   Este archivo solo crea vistas "marcador" (PENDIENTE) si todavía no existen, para que la
--   verificación nunca falle por una vista faltante. No cambia tus vistas existentes.
--   La respuesta esperada se calcula desde ORDERS (no usa tus vistas, tampoco MENSUAL_1995).
--   Los importes se comparan con ROUND(..., 2) en la respuesta esperada.
-- =====================================================================

-- Marcadores: si un objeto aún no existe, se crea con la línea PENDIENTE.
